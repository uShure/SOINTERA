  // Определение этапа воронки
  private determineFunnelStage(message: string, conversationHistory: any[], classification: string): string {
    const lowerMessage = message.toLowerCase();

    // Если это первое сообщение
    if (conversationHistory.length === 0) return 'initial';

    // Если задаем вопросы
    const hasQuestions = conversationHistory.some(msg =>
      msg.role === 'assistant' && msg.content.includes('Давайте я вам задам')
    );
    if (hasQuestions && !this.isAnsweringQuestions(message)) return 'qualification';

    // Если показываем курс
    const hasPresentation = conversationHistory.some(msg =>
      msg.role === 'assistant' && msg.content.includes('отличная возможность прокачаться')
    );
    if (hasPresentation && !this.isPriceQuestion(message)) return 'presentation';

    // Если обсуждаем цену
    if (this.isPriceQuestion(message) || this.isMentioningPrice(conversationHistory)) {
      return 'pricing';
    }

    // Если есть возражения
    if (this.hasObjections(message)) return 'objection';

    // Если готов купить
    if (classification === 'ready_to_buy') return 'closing';

    return 'qualification';
  }

  // Проверка на ответы на вопросы
  private isAnsweringQuestions(message: string): boolean {
    const answerPatterns = [
      'работаю', 'лет', 'опыт', 'мастер', 'салон', 'клиенты',
      'не хватает', 'хочу изучить', 'нужно', 'проблема'
    ];
    return answerPatterns.some(pattern => message.toLowerCase().includes(pattern));
  }

  // Проверка на вопросы о цене
  private isPriceQuestion(message: string): boolean {
    const pricePatterns = ['цена', 'стоимость', 'сколько', 'цену', 'рублей', 'оплат'];
    return pricePatterns.some(pattern => message.toLowerCase().includes(pattern));
  }

  // Проверка упоминания цены в истории
  private isMentioningPrice(conversationHistory: any[]): boolean {
    return conversationHistory.some(msg =>
      msg.role === 'assistant' && (
        msg.content.includes('₽') ||
        msg.content.includes('рублей') ||
        msg.content.includes('стоимость')
      )
    );
  }

  // Проверка на возражения
  private hasObjections(message: string): boolean {
    const objectionPatterns = [
      'дорого', 'дорого', 'времени нет', 'не уверен', 'подумаю',
      'сомневаюсь', 'не готов', 'позже', 'не сейчас'
    ];
    return objectionPatterns.some(pattern => message.toLowerCase().includes(pattern));
  }

  // Извлечение интереса к курсам
  private extractCourseInterest(message: string, conversationHistory: any[]): string | undefined {
    const lowerMessage = message.toLowerCase();

    // Прямые упоминания курсов
    if (lowerMessage.includes('фундамент')) return 'Фундамент';
    if (lowerMessage.includes('днк') || lowerMessage.includes('цвет')) return 'ДНК цвета';
    if (lowerMessage.includes('наставник')) return 'Наставник';
    if (lowerMessage.includes('стрижк')) return 'Стрижки';
    if (lowerMessage.includes('колорист')) return 'Колористика';

    // Анализ истории
    const allMessages = conversationHistory.map(m => m.content.toLowerCase()).join(' ');
    if (allMessages.includes('фундамент')) return 'Фундамент';
    if (allMessages.includes('днк') || allMessages.includes('цвет')) return 'ДНК цвета';

    return undefined;
  }

